"""Window sweep (EXPERIMENTS/protocol/window_sweep.json): one fixed, tuned config per sweep, only the length changes.

    python -m EXPERIMENTS.tuning.window_sweep --jobs EXPERIMENTS/results_v2/window_sweep_jobs.json

Reset windows take FE_cell_w50_full's changes with 'window' set; carried state takes FE_A0's with 'chunk' set.
Seeds 10-14. w50 and carry200 reuse finished runs (sources()), so only their missing seeds are run.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from EXPERIMENTS.paths import PROTOCOL_DIR
from EXPERIMENTS.pipeline import spec as SPEC
from EXPERIMENTS.pipeline.settings import strip_retired
from EXPERIMENTS.protocol import protocol as PT
from EXPERIMENTS.tuning import make_specs as MS, select as SEL

P = json.loads((PROTOCOL_DIR / 'window_sweep.json').read_text())
REF = {'reset': ('FE_cell_w50_full', 'window'), 'carry': ('FE_A0', 'chunk')}
REUSED = {'w50': [('FE_cell_w50_full', s) for s in (10, 11, 12)],
          'carry200': [('FE_cell_carry_2s', s) for s in (10, 11, 12)] + [('FE_A0', s) for s in (13, 14)]}


def _spec(i, changes, d):
    raw = {'id': i, 'title': f'Window sweep: {i[7:]}', 'tags': ['study v2', 'window_sweep'], 'changes': changes,
           'description': 'Window sweep arm (generated by EXPERIMENTS/tuning/window_sweep.py; EXPERIMENTS/protocol/window_sweep.json).'}
    path = Path(d) / f'{i}.json'
    if not MS.keep_existing(path, changes):
        SPEC.parse(raw, i)
        path.write_text(json.dumps(raw, indent=1) + '\n', encoding='utf-8')
    return i


def write(configs_dir=None) -> list[str]:
    """Write one FE_win_<arm> spec per arm that runs anything (carry200 is A0 itself); return the ids."""
    d = Path(configs_dir or SPEC.CONFIGS)
    ids = []
    for kind, (ref, key) in REF.items():
        base = strip_retired(dict(SPEC.load(ref, d).changes))
        for arm, length in P['arms'][kind].items():
            if arm == 'carry200':
                continue
            ids.append(_spec(f'FE_win_{arm}', dict(base, **{key: length}), d))
    return ids


def _seeds(arm):
    have = {s for _, s in REUSED.get(arm, [])}
    return [s for s in P['seeds'] if s not in have]


def sources() -> dict[str, list[tuple[str, int]]]:
    """arm -> the (spec id, seed) runs it is scored from."""
    arms = [a for k in REF for a in P['arms'][k]]
    return {a: REUSED.get(a, []) + [(f'FE_win_{a}', s) for s in _seeds(a)] for a in arms}


def jobs(ids, people) -> list[list]:
    """[exp, person, direction, seed], longest arms first (reset windows by length, then carried state, then w50)."""
    def rank(i):
        arm = i[len('FE_win_'):]
        return (0, -P['arms']['reset'][arm]) if arm in P['arms']['reset'] and arm != 'w50' else \
               (1, -P['arms']['carry'][arm]) if arm in P['arms']['carry'] else (2, 0)
    return [[i, p, SEL.DIRECTION, s] for i in sorted(ids, key=rank) for s in _seeds(i[len('FE_win_'):]) for p in people]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', required=True)
    a = ap.parse_args(argv)
    j = jobs(write(), PT.load()['people'])
    Path(a.jobs).write_text(json.dumps(j) + '\n')
    print(f'{len(j)} runs -> {a.jobs}')


if __name__ == '__main__':
    main()
