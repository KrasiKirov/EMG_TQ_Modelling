"""Write the study v2 specs: TS2_<round>_<cell>_<name>.json = protocol fixed settings + cell + network + protocol.

    python -m EXPERIMENTS.tuning.make_specs --round R1            # write R1 specs of every active cell, print the ids
    python -m EXPERIMENTS.tuning.make_specs --round R1 --cell w200_full   # one cell (a gate screen)

Active cells: the 6 always-run live cells (full overlap or carried state; the overlap cells were retired on 2026-11-24,
protocol.live_cells). Under the 6-day budget a gated length
that passes its check is not tuned (protocol budget.tune_gated). R1 = coarse (6 shared draws + anchor), R2 = fine
(4 draws around the cell's best R1 config, 2 after the budget step fine_2), R3 = the best 2 of R1 + R2 with seed 1
added (reuses their specs, so it writes nothing). Every round trains to early stopping under the 400-epoch cap.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from EXPERIMENTS.pipeline import spec as SPEC
from EXPERIMENTS.protocol import protocol as PT
from EXPERIMENTS.tuning import budget as BG, space as SPC

_P = PT.load()


def spec_id(rnd: str, cell: str, name: str) -> str:
    return f'TS2_{rnd}_{cell}_{name}'


def changes(rnd: str, cell: str, config: dict) -> dict:
    return {**_P['fixed'], **SPC.changes(cell), **config, 'train_protocol': _P['rounds'][rnd]['protocol']}


def write(rnd: str, cell: str, configs: dict[str, dict], configs_dir: Path | str | None = None) -> list[str]:
    """Write one spec per config; return the ids. An existing spec with other changes raises (results would mix)."""
    d = Path(configs_dir or SPEC.CONFIGS)
    ids = []
    for name, cfg in configs.items():
        i = spec_id(rnd, cell, name)
        raw = {'id': i, 'title': f'Study v2 {rnd}, {cell}, {name}',
               'description': 'Study v2 search run (generated by EXPERIMENTS/tuning/make_specs.py).',
               'tags': ['study v2', rnd], 'changes': changes(rnd, cell, cfg)}
        path = d / f'{i}.json'
        if path.exists() and json.loads(path.read_text())['changes'] != raw['changes']:
            raise SPEC.SpecError(f'{path} exists with different changes')
        SPEC.parse(raw, i)
        path.write_text(json.dumps(raw, indent=1) + '\n', encoding='utf-8')
        ids.append(i)
    return ids


def active_cells(results_dir=None) -> list[str]:
    """Live cells that run R1-R3: the always-run ones, plus a gated length whose gate passed when the budget tunes
    gated lengths (protocol budget.tune_gated)."""
    from EXPERIMENTS.paths import RESULTS_V2
    rd = Path(results_dir or RESULTS_V2)
    live = PT.live_cells(_P)
    out = [c for c, v in live.items() if not v['gated']]
    for g in _P['gates']['order'] if _P['budget']['tune_gated'] else []:
        f = rd / f'gate_{g}.json'
        if not (f.exists() and json.loads(f.read_text())['continues']):
            break
        out += [c for c, v in live.items() if v['gated'] and v['window'] == live[g]['window']]
    return out


def for_round(rnd: str, cell: str) -> list[str]:
    from EXPERIMENTS.tuning import select as SEL
    if rnd == 'R1':
        return write('R1', cell, SPC.configs(cell))
    if rnd == 'R2':
        best = SEL.best_r1(cell, _P['people'])
        center = SPC.configs(cell)[best.rsplit('_', 1)[1]]
        return write('R2', cell, SPC.fine_configs(cell, center, n=BG.fine_n()))
    return SEL.r3_ids(cell, _P['people'])


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--round', required=True, choices=list(_P['rounds']))
    ap.add_argument('--cell', nargs='*')
    a = ap.parse_args(argv)
    cells = a.cell or active_cells()
    print(' '.join(i for c in cells for i in for_round(a.round, c)))


if __name__ == '__main__':
    main()
