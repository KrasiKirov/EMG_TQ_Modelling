"""Final runs of study v2 (decisions D5, D26) from results_v2/choice.json: fresh seeds, no new configs.

    python -m EXPERIMENTS.tuning.finalize --jobs EXPERIMENTS/results_v2/final_jobs.json

Writes the FE_ specs and a run_queue jobs file ([exp, subject, direction, seed] per run):
  FE_cell_<cell>  each cell winner, seeds 10-12, S1->S2
  FE_A0           the chosen setting, seeds 10-19, S1->S2 (the only direction, D1); seeds 10-12 are the same runs as
                  its cell winner's (same changes, same seeds), so only 13-19 are run and confirm.py reads 10-12 there
  FE_A1           lagged ridge (alpha per person chosen on session-1 validation inside the run), 1 run
  FE_A2           last semester's network at 0.2 s, full overlap, v2 training, seeds 10-19
  FE_A3           A0 with total torque (passive 'none'), seeds 10-19
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from EXPERIMENTS.pipeline import spec as SPEC
from EXPERIMENTS.pipeline.run import RESULTS_V2
from EXPERIMENTS.protocol import protocol as PT
from EXPERIMENTS.tuning import make_specs as MS, space as SPC

_P = PT.load()


def _spec(i, title, changes, d):
    raw = {'id': i, 'title': title, 'tags': ['study v2', 'final'], 'changes': changes,
           'description': 'Study v2 final run (generated by EXPERIMENTS/tuning/finalize.py from choice.json).'}
    path = Path(d) / f'{i}.json'
    if path.exists() and json.loads(path.read_text())['changes'] != changes:
        raise SPEC.SpecError(f'{path} exists with different changes')
    SPEC.parse(raw, i)
    path.write_text(json.dumps(raw, indent=1) + '\n', encoding='utf-8')
    return i


def write(choice: dict, configs_dir=None) -> list[tuple[str, str, str, list[int]]]:
    """Write the FE_ specs; return (spec id, person, direction, seeds) per arm and person."""
    d = Path(configs_dir or SPEC.CONFIGS)
    fs, people = _P['final_seeds'], _P['people']
    s1 = _P['primary_direction']
    load = lambda i: dict(SPEC.load(i, d).changes)
    arms = []                                            # (id, directions, seeds)
    for cell, wid in choice['cell_winners'].items():
        arms.append((_spec(f'FE_cell_{cell}', f'Study v2 final: winner of {cell}', load(wid), d), [s1], fs['cell']))
    a0 = load(choice['A0'])
    _spec('FE_A0', 'Study v2 final: A0 (chosen setting)', a0, d)
    shared = fs['cell'] if choice['A0'] in choice['cell_winners'].values() else []
    arms.append(('FE_A0', [s1], [s for s in fs['A0'] if s not in shared]))
    a1 = {**_P['fixed'], 'model': 'ridge_lagged', 'window': max(_P['ridge']['lags_steps']) + 1}
    arms.append((_spec('FE_A1', 'Study v2 final: A1 lagged ridge', a1, d), [s1], [fs['A0'][0]]))
    a2 = MS.changes('R3', 'w20_full', SPC.ANCHOR)
    arms.append((_spec('FE_A2', "Study v2 final: A2 last semester's network, v2 training", a2, d), [s1], fs['A2']))
    arms.append((_spec('FE_A3', 'Study v2 final: A3 = A0 with total torque', dict(a0, passive='none'), d), [s1], fs['A3']))
    return [(i, p, dr, list(seeds)) for i, dirs, seeds in arms for dr in dirs for p in people]


def jobs(plan) -> list[list]:
    return [[i, p, dr, s] for i, p, dr, seeds in plan for s in seeds]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', required=True)
    a = ap.parse_args(argv)
    choice = json.loads((Path(RESULTS_V2) / 'choice.json').read_text())
    j = jobs(write(choice))
    Path(a.jobs).write_text(json.dumps(j) + '\n')
    print(f'{len(j)} runs -> {a.jobs}')


if __name__ == '__main__':
    main()
