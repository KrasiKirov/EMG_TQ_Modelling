"""Second fine round of study v2 (EXPERIMENTS/protocol/fine_round_2.json): a precision check of the tuning, run
after every study v2 result was seen, so a sensitivity analysis (deviations.json). It never rewrites choice.json.

    python -m EXPERIMENTS.tuning.fine2 --jobs EXPERIMENTS/results_v2/fine_round_2_jobs.json   # specs + jobs
    python -m EXPERIMENTS.tuning.fine2 --select                                               # after the runs

Per cell (carry_2s, w50_full, w100_full): TS2_R4_<cell>_g0..g3 = 4 fine draws around the cell winner (seeds 0-2) and
TS2_R4_<cell>_w = the winner's settings unchanged, seed 2 only; the winner's seeds 0 and 1 are read from its own id.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from EXPERIMENTS.paths import RESULTS_V2
from EXPERIMENTS.pipeline import spec as SPEC
from EXPERIMENTS.pipeline.settings import strip_retired
from EXPERIMENTS.protocol import protocol as PT
from EXPERIMENTS.tuning import halving as HV, make_specs as MS, select as SEL, space as SPC

P = json.loads((PT.HERE / 'fine_round_2.json').read_text())
_S2 = PT.load()
NET = ('units', 'layers', 'dropout', 'lr', 'batch')


def configs(cell: str, centre: dict) -> dict[str, dict]:
    """{'g0'..'g3'}: study v2's fine draws around ``centre`` with this round's seed (batch dropped for carried state)."""
    carry = _S2['cells'][cell].get('state') == 'carry'
    c = dict(centre, batch=centre.get('batch', 64))
    out = {f'g{i}': d for i, d in enumerate(SPC.fine_draws(c, P['draws']['n'], P['draws']['seed']))}
    return {k: {kk: vv for kk, vv in v.items() if not (carry and kk == 'batch')} for k, v in out.items()}


def _spec(i, title, changes, d):
    raw = {'id': i, 'title': title, 'tags': ['study v2', 'R4', 'fine_round_2'], 'changes': changes,
           'description': 'Second fine round (generated by EXPERIMENTS/tuning/fine2.py; EXPERIMENTS/protocol/fine_round_2.json).'}
    path = Path(d) / f'{i}.json'
    if not MS.keep_existing(path, changes):
        SPEC.parse(raw, i)
        path.write_text(json.dumps(raw, indent=1) + '\n', encoding='utf-8')
    return i


def write(cell_winners: dict, configs_dir=None) -> list[str]:
    """Write the round's specs for its cells; return the ids (per cell: g0..g3, then w)."""
    d = Path(configs_dir or SPEC.CONFIGS)
    ids = []
    for cell in P['cells']:
        win = strip_retired(dict(SPEC.load(cell_winners[cell], d).changes))
        centre = {k: win[k] for k in NET if k in win}
        for name, cfg in configs(cell, centre).items():
            ids.append(_spec(f'TS2_R4_{cell}_{name}', f'Study v2 R4, {cell}, {name}',
                             MS.changes('R3', cell, cfg), d))
        ids.append(_spec(f'TS2_R4_{cell}_w', f'Study v2 R4, {cell}, winner {cell_winners[cell]} (seed 2)', win, d))
    return ids


def jobs(ids, people) -> list[list]:
    """[exp, person, direction, seed], one per run: draws on seeds 0-2, the winner copy on seed 2."""
    return [[i, p, SEL.DIRECTION, s] for i in ids
            for s in (P['seeds']['winner'] if i.endswith('_w') else P['seeds']['draws']) for p in people]


def _table(sources, people, results_dir, kind='full'):
    """{config: {person: median over its (id, seed) sources of validation nMAE}}."""
    out = {}
    for name, src in sources.items():
        per = [SEL.load_val([i], [s], people, results_dir)[0][kind][i] for i, s in src]
        out[name] = {p: float(np.median([t[p] for t in per])) for p in people}
    return out


def cell_winner(cell: str, winner: str, people, results_dir=None) -> str:
    """Paired 1-SE winner (fewest parameters) among the cell's winner and g0..g3, each on seeds 0-2."""
    rd = results_dir or RESULTS_V2
    src = {winner: [(winner, 0), (winner, 1), (f'TS2_R4_{cell}_w', 2)]}
    for k in range(P['draws']['n']):
        g = f'TS2_R4_{cell}_g{k}'
        src[g] = [(g, s) for s in P['seeds']['draws']]
    params = SEL.n_params(list(src), people, rd)
    return SEL.winner(_table(src, people, rd), params)


def choose_a0(choice: dict, new_winners: dict, people, results_dir=None) -> str:
    """study v2's A0 rule over the live cells' winners on seeds 0 and 1; A0 is kept when no winner changed."""
    if all(choice['cell_winners'][c] == w for c, w in new_winners.items()):
        return choice['A0']
    winners = {c: new_winners.get(c, w) for c, w in choice['cell_winners'].items()
               if not PT.retired_cell(_S2['cells'][c])}
    tables, _ = SEL.load_val(list(winners.values()), [0, 1], people, results_dir)
    return HV.keep(tables['common'], 1)[0]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', help='write the specs and this run_queue jobs file')
    ap.add_argument('--select', action='store_true', help='pick the cell winners and A0 (writes fine_round_2.json)')
    a = ap.parse_args(argv)
    choice = json.loads((Path(RESULTS_V2) / 'choice.json').read_text())
    people = _S2['people']
    if a.jobs:
        j = jobs(write(choice['cell_winners']), people)
        Path(a.jobs).write_text(json.dumps(j) + '\n')
        print(f'{len(j)} runs -> {a.jobs}')
    if a.select:
        new = {c: cell_winner(c, choice['cell_winners'][c], people) for c in P['cells']}
        res = {'cell_winners': new, 'changed': {c: w for c, w in new.items() if w != choice['cell_winners'][c]},
               'A0': choose_a0(choice, new, people), 'A0_before': choice['A0'],
               'protocol': 'fine_round_2', 'parent_protocol_hash': _S2['hash']}
        (Path(RESULTS_V2) / 'fine_round_2.json').write_text(json.dumps(res, indent=1) + '\n')
        print(json.dumps(res, indent=1))
    if not (a.jobs or a.select):
        ap.error('give --jobs or --select')


if __name__ == '__main__':
    main()
